@pytest.mark.skipif(not DATABASE_URL, reason="DATABASE_URL is not set")
def test_switch_on_a_throwaway_copy():
    import psycopg

    conn = psycopg.connect(DATABASE_URL)
    try:
        cur = conn.cursor()
        if cur.execute("select to_regclass('public.v2_firms')").fetchone()[0] is not None:
            pytest.skip("this database already has v2_firms; the dry-run only builds a throwaway copy")
        if cur.execute("select to_regclass('bots.ingest_keys')").fetchone()[0] is None:
            raise AssertionError("bots.ingest_keys is missing; run migrations before this test")
        cur.execute(FIXTURE)
        cur.execute(
            """
            insert into bots.ingest_keys (name, key_hash, bot_id, active) values
              ('v2-auto-publish-test-bot', 'test-only-not-a-key', 'v2-auto-publish-test-bot', true),
              ('v2-auto-publish-test-bot-b', 'test-only-not-a-key-b', 'v2-auto-publish-test-bot-b', true),
              ('v2-auto-publish-test-checker', 'test-only-not-a-key-checker', 'toxy-checker', true)
            """
        )
        cur.execute(MIG)
        cur.execute(TEST)
        cur.execute(UNDO)
        body = cur.execute(
            "select pg_get_functiondef('public.v2_research_submit(uuid,jsonb,boolean)'::regprocedure)"
        ).fetchone()[0]
        assert "v2_auto_publish_apply_submission" not in body
        checker = cur.execute(
            "select pg_get_functiondef('public.v2_checker_action(uuid,text,jsonb,boolean)'::regprocedure)"
        ).fetchone()[0]
        assert "v2_auto_publish_checker_reject" not in checker
        assert "external-checker-1" in checker
        assert cur.execute("select to_regclass('public.v2_auto_publish')").fetchone()[0] is None
        key = cur.execute(
            "select id from bots.ingest_keys where name = 'v2-auto-publish-test-bot'"
        ).fetchone()[0]
        startup = cur.execute(
            "select startup_id from public.v2_startups where startup_name = 'Auto Publish Existing'"
        ).fetchone()[0]
        reply = cur.execute(
            """
            select public.v2_research_submit(%s, jsonb_build_array(jsonb_build_object(
              'table', 'v2_deals', 'box', 'D1', 'firm_id', '186',
              'fact', jsonb_build_object(
                'startup_id', %s::bigint,
                'deal_date', '2020-10-01',
                'round_amount', 10,
                'source_url', 'https://portfolio.example.test/after-rollback',
                'source_level', '2',
                'source_date', '2020-01-15',
                'source_type', 'Firm website')
            )), false)
            """,
            (key, startup),
        ).fetchone()[0]
        if isinstance(reply, str):
            reply = json.loads(reply)
        assert reply["ok"] is True, reply
        assert reply["accepted"] == 1, reply
        hidden = cur.execute(
            """
            select is_current, shown from public.v2_deals
            where firm_id = 186 and deal_date = date '2020-10-01'
            """
        ).fetchone()
        assert hidden == (False, False)
    finally:
        conn.rollback()
        conn.close()
