"""Auto-publish switch: off leaves the door unchanged, on shows one firm's rows immediately."""
import json
import os
import pathlib

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
MIG = (ROOT / "supabase/migrations/20261110120000_v2_auto_publish.sql").read_text(encoding="utf-8")
UNDO = (ROOT / "supabase/rollbacks/20261110120000_v2_auto_publish.sql").read_text(encoding="utf-8")
TEST = (ROOT / "supabase/tests/v2_auto_publish.sql").read_text(encoding="utf-8")
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()


def test_migration_is_off_by_default_and_keeps_the_queue_open():
    assert "v2 schema missing, skipped" in MIG
    assert "values (true, false, '{}')" in MIG
    assert MIG.count("PERFORM public.v2_auto_publish_apply_submission(sid);") == 4
    assert "v2_auto_publish_checker_reject" in MIG
    assert "Confirmed: website already filled" in MIG
    assert "skipped: new firm stays with the Checker" in MIG
    assert "v2_auto_publish_shared" in MIG
    assert "enable row level security" in MIG
    assert "revoke all on function public.v2_auto_publish_set(boolean, bigint[]) from public" in MIG
    assert "grant execute on function public.v2_auto_publish_set(boolean, bigint[]) to service_role" in MIG
    assert "delete from public.v2_" not in MIG.lower()
    assert "update public.v2_change_log" not in MIG.lower()
    assert "update v2_change_log" not in MIG.lower()
    assert "Not applied to production" in MIG


def test_rollback_restores_the_door_and_drops_the_switch():
    assert "v2_auto_publish_apply_submission" not in UNDO.split("drop function", 1)[0]
    assert "v2_auto_publish_checker_reject" not in UNDO.split("drop function", 1)[0]
    assert "drop table if exists public.v2_auto_published" in UNDO
    assert "drop table if exists public.v2_auto_publish" in UNDO
    assert "external-checker-1" in UNDO
    assert "delete from" not in UNDO.lower()
    assert "Pull them down before running this" in UNDO


def test_sql_script_covers_the_switch_cases():
    for label in (
        "switch must start off",
        "off deal should stay hidden",
        "firm 186 deal should be live",
        "firm 8 must stay hidden",
        "rejected item created a live deal",
        "L4 must stay archived",
        "held legal name was not applied",
        "checker reject should restore the prior legal name",
        "rejected deal still matches a page predicate",
        "confirm of an already-filled website failed",
        "backfill published firm 8",
        "shared startup disappeared",
        "firm pull hid the other firm deal",
        "backfill must not republish a pull",
        "restore brought back a Checker-rejected deal",
        "turning the switch off hid a row",
        "switch off should hide the next submission",
        "anon or authenticated can reach the switch",
        "change log accepted an update",
    ):
        assert label in TEST


