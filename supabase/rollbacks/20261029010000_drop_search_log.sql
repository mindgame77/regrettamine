create view bots.search_log_current with (security_invoker = true) as
 SELECT id,
    firm_id,
    registry_id,
    bot_id,
    section,
    source_site,
    query,
    searched_at,
    result,
    item_count,
    enrichment_id,
    submission_id,
    created_at,
    name_only
   FROM bots.search_log l
  WHERE ((enrichment_id IS NULL) OR (enrichment_id = ( SELECT e2.id
           FROM (bots.research_enrichments e
             JOIN bots.research_enrichments e2 ON ((e2.valid AND (e2.bot_id = e.bot_id) AND (COALESCE((e2.firm_id)::text, e2.registry_id) = COALESCE((e.firm_id)::text, e.registry_id)))))
          WHERE (e.id = l.enrichment_id)
          ORDER BY e2.received_at DESC, e2.id DESC
         LIMIT 1)));
grant select, insert, update, delete on bots.search_log_current to bot_writer, service_role;

