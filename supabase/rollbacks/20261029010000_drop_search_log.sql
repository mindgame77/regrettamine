create view public.firm_site_coverage as
 SELECT COALESCE(f.slug, l.registry_id) AS firm,
    l.firm_id,
    l.registry_id,
    l.section,
    l.source_site,
    count(*) AS searches,
    count(*) FILTER (WHERE (l.result = 'found'::text)) AS found,
    count(*) FILTER (WHERE (l.result = 'none'::text)) AS "none",
    count(*) FILTER (WHERE (l.result = 'blocked'::text)) AS blocked,
    count(*) FILTER (WHERE (l.result = 'error'::text)) AS error,
    sum(l.item_count) AS items,
    max(l.searched_at) AS last_searched
   FROM (bots.search_log_current l
     LEFT JOIN firms f ON ((f.id = l.firm_id)))
  GROUP BY COALESCE(f.slug, l.registry_id), l.firm_id, l.registry_id, l.section, l.source_site;

create view public.site_search_stats as
 SELECT source_site,
    count(*) AS searches,
    count(DISTINCT COALESCE((firm_id)::text, registry_id)) AS firms,
    round(avg(((result = 'found'::text))::integer), 3) AS found_rate,
    round(avg(((result = 'none'::text))::integer), 3) AS none_rate,
    round(avg(((result = 'blocked'::text))::integer), 3) AS blocked_rate,
    round(avg(((result = 'error'::text))::integer), 3) AS error_rate
   FROM bots.search_log_current
  GROUP BY source_site;

